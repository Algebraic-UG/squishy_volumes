use std::{fmt::Write as _, path::PathBuf};

use strum::IntoEnumIterator as _;

use squishy_volumes_util::{
    ParticleFlags,
    attribute::{Key, Trait, Visitor},
};

use crate::{FrameBulkCollider, FrameBulkParticles};

const UPDATE_ENV_VAR: &str = "SQUISHY_VOLUMES_UPDATE_GOLDEN";

const GENERATED_NOTE: &str = "# Generated by the python_constants test of squishy_volumes_file_input.\n\
     # Regenerate with SQUISHY_VOLUMES_UPDATE_GOLDEN=1 cargo test -p squishy_volumes_file_input\n";

fn golden_path(file_name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../../python/src/squishy_volumes_extension")
        .join(file_name)
}

fn screaming_snake_case(camel_case: &str) -> String {
    let mut result = String::new();
    for (i, c) in camel_case.chars().enumerate() {
        if c.is_uppercase() && i > 0 {
            result.push('_');
        }
        result.push(c.to_ascii_uppercase());
    }
    result
}

fn python_literal(debug: String) -> String {
    debug.replace('[', "(").replace(']', ")")
}

fn named_tuple_class(name: &str, fields: &[(&str, &str)]) -> String {
    let mut class =
        format!("{GENERATED_NOTE}\nfrom typing import NamedTuple\n\n\nclass {name}(NamedTuple):\n");
    for (field, annotation) in fields {
        writeln!(class, "    {field}: {annotation}").unwrap();
    }
    class.push_str("\n\n");
    class
}

struct AttributeRenderer;

impl Visitor for AttributeRenderer {
    type Output = String;

    fn visit<A: Trait>(&mut self) -> String {
        let key = format!("{:?}", A::KEY);
        format!(
            "{} = OutputAttribute(\n    key=\"{key}\",\n    name=\"{}\",\n    default={},\n)\n",
            screaming_snake_case(&key),
            A::ALEMBIC_NAME,
            python_literal(format!("{:?}", A::DEFAULT)),
        )
    }
}

fn render_output_attributes() -> String {
    let mut body = named_tuple_class(
        "OutputAttribute",
        &[
            ("key", "str"),
            ("name", "str"),
            ("default", "float | tuple[float, ...]"),
        ],
    );
    for key in Key::iter() {
        body.push_str(&key.visit(&mut AttributeRenderer));
    }
    body.push_str("\nPARTICLE_FLAG_BITS = {\n");
    for (name, flag) in ParticleFlags::all().iter_names() {
        writeln!(body, "    \"{name}\": {},", flag.bits().trailing_zeros()).unwrap();
    }
    body.push_str("}\n");
    body
}

struct InputAttribute {
    constant: String,
    key: String,
    name: String,
}

impl InputAttribute {
    fn new(prefix: &str, key: String) -> Self {
        let snake_case = screaming_snake_case(&key);
        let name = format!("sv_{}", snake_case.to_ascii_lowercase());
        let constant = format!("{prefix}{snake_case}");
        Self {
            constant,
            key,
            name,
        }
    }

    fn render(&self) -> String {
        format!(
            "{} = InputAttribute(\n    key=\"{}\",\n    name=\"{}\",\n)\n",
            self.constant, self.key, self.name
        )
    }
}

fn particle_attributes() -> Vec<InputAttribute> {
    FrameBulkParticles::iter()
        .map(|variant| InputAttribute::new("PARTICLE_", format!("{variant:?}")))
        .collect()
}

fn collider_attributes() -> Vec<InputAttribute> {
    FrameBulkCollider::iter()
        .filter(|variant| *variant != FrameBulkCollider::Triangles)
        .map(|variant| InputAttribute::new("COLLIDER_", format!("{variant:?}")))
        .collect()
}

fn render_tuple(name: &str, attributes: &[InputAttribute]) -> String {
    let mut tuple = format!("{name} = (\n");
    for attribute in attributes {
        writeln!(tuple, "    {},", attribute.constant).unwrap();
    }
    tuple.push_str(")\n");
    tuple
}

fn render_input_attributes() -> String {
    let mut body = named_tuple_class("InputAttribute", &[("key", "str"), ("name", "str")]);
    let particles = particle_attributes();
    let colliders = collider_attributes();
    for attribute in particles.iter().chain(&colliders) {
        body.push_str(&attribute.render());
    }
    body.push('\n');
    body.push_str(&render_tuple("PARTICLE_ATTRIBUTES", &particles));
    body.push_str(&render_tuple("COLLIDER_ATTRIBUTES", &colliders));
    body
}

fn license_header() -> String {
    include_str!("python_constants.rs")
        .lines()
        .take_while(|line| !line.is_empty())
        .map(|line| format!("#{}\n", line.trim_start_matches("//")))
        .collect()
}

fn split_header(content: &str) -> (&str, &str) {
    match content.find("\n\n") {
        Some(end) if content.starts_with("# SPDX") => content.split_at(end + 2),
        _ => ("", content),
    }
}

fn check_golden(file_name: &str, expected: String) {
    let path = golden_path(file_name);
    let existing = std::fs::read_to_string(&path).unwrap_or_default();
    let (header, body) = split_header(&existing);

    if std::env::var_os(UPDATE_ENV_VAR).is_some() {
        let header = if header.is_empty() {
            format!("{}\n", license_header())
        } else {
            header.to_string()
        };
        std::fs::write(&path, header + &expected).unwrap();
        return;
    }

    assert_eq!(
        body,
        expected,
        "{} is out of date, regenerate it with {UPDATE_ENV_VAR}=1 cargo test -p squishy_volumes_file_input",
        path.display()
    );
}

#[test]
fn python_output_attributes_match_rust() {
    check_golden("output_attributes.py", render_output_attributes());
}

#[test]
fn python_input_attributes_match_rust() {
    check_golden("input_attributes.py", render_input_attributes());
}
